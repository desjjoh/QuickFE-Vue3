import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

const root = fileURLToPath(new URL('../../', import.meta.url))
const normalize = (value) => value.split(path.sep).join('/')
async function walk(directory) {
  const entries = await readdir(path.join(root, directory), { withFileTypes: true })
  const lists = await Promise.all(
    entries.map((entry) =>
      entry.isDirectory() ? walk(`${directory}/${entry.name}`) : [`${directory}/${entry.name}`],
    ),
  )
  return lists.flat().sort()
}
const files = [...(await walk('src')), ...(await walk('test'))]
const codeFiles = files.filter((file) => /\.(ts|vue)$/.test(file))
const contents = new Map(
  await Promise.all(
    codeFiles.map(async (file) => [file, await readFile(path.join(root, file), 'utf8')]),
  ),
)
const imports = new Map()
for (const [file, content] of contents) {
  const dependencies = new Set()
  // Import references are discovery evidence, not proof that behavior is asserted.
  const references = [
    ...content.matchAll(/(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s*)['"]([^'"]+)['"]/g),
  ]
  for (const [, reference] of references) {
    let base
    if (reference.startsWith('@/')) base = `src/${reference.slice(2)}`
    else if (reference.startsWith('@test/')) base = `test/${reference.slice(6)}`
    else if (reference.startsWith('.'))
      base = normalize(path.posix.join(path.posix.dirname(file), reference))
    else continue
    const dependency = [base, `${base}.ts`, `${base}.vue`, `${base}/index.ts`].find((candidate) =>
      contents.has(candidate),
    )
    if (dependency) dependencies.add(dependency)
  }
  imports.set(file, dependencies)
}
function category(file) {
  if (/\.(spec|test)\.ts$/.test(file) || file.includes('/__tests__/') || file.startsWith('test/'))
    return null
  if (/\/helpers\//.test(file) || /Utils\.ts$/.test(file)) return 'Helpers'
  if (/\/hooks\//.test(file)) return 'Hooks'
  if (/^src\/library\/models\/.+\.ts$/.test(file)) return 'Models'
  if (/^src\/shared\/api\/.+\.ts$/.test(file)) return 'API adapters'
  if (/\/stores\/.+\.ts$/.test(file)) return 'Stores'
  if (file.endsWith('.vue'))
    return file.startsWith('src/library/') || file.startsWith('src/shared/')
      ? 'Shared components and layouts'
      : 'Application components and views'
  return null
}
const sources = codeFiles.filter((file) => category(file))
const tests = codeFiles.filter((file) => /\.(spec|test)\.ts$/.test(file))
const reachable = new Map()
for (const test of tests) {
  const found = new Set()
  const pending = [...imports.get(test)]
  while (pending.length) {
    const file = pending.pop()
    if (found.has(file)) continue
    found.add(file)
    pending.push(...(imports.get(file) ?? []))
  }
  reachable.set(test, found)
}
const usage = (file) =>
  [...imports].filter(
    ([importer, dependencies]) =>
      !tests.includes(importer) &&
      !importer.startsWith('test/') &&
      !importer.includes('/__tests__/') &&
      dependencies.has(file),
  ).length
const priority = (file) => {
  if (/\/playground\/|\/template\//.test(file)) return 'P3'
  if (['Helpers', 'Hooks', 'Models', 'API adapters', 'Stores'].includes(category(file))) return 'P1'
  if (
    /\/components\/(inputs|table|modal|offcanvas|dropdowns|tabs|error)\//.test(file) ||
    /\/layouts\/Form/.test(file)
  )
    return 'P1'
  return 'P2'
}
const link = (file) => `[${file}](../${file})`
const groups = [
  'Helpers',
  'Hooks',
  'Shared components and layouts',
  'Models',
  'API adapters',
  'Stores',
  'Application components and views',
]
let output = '# Test inventory\n\n'
output +=
  'Generated by `npm run test:inventory`. Refresh after adding or moving source files or suites.\n\n'
output +=
  '**This is a source-to-suite reference map, not a coverage report.** Direct references can be mocked or type-only; indirect references only indicate reachability through imports. E2E route coverage and auto-registered components require the manual behavior review in [the testing standards](testing-standards.md). No row is considered fully tested from imports alone.\n\n'
output +=
  'P1: shared behavior, contracts, state, inputs, and overlays. P2: remaining production presentation and views. P3: playground and template examples. Importer counts rank reuse within each priority; they omit dynamic registration and template-only references.\n\n'
output +=
  '| Area | Items | Direct suite references | Indirect only | No isolated suite reference |\n| --- | ---: | ---: | ---: | ---: |\n'
const mapping = new Map(
  sources.map((file) => [
    file,
    {
      direct: tests.filter((test) => imports.get(test).has(file)),
      indirect: tests.filter(
        (test) => !imports.get(test).has(file) && reachable.get(test).has(file),
      ),
    },
  ]),
)
for (const group of groups) {
  const members = sources.filter((file) => category(file) === group)
  const direct = members.filter((file) => mapping.get(file).direct.length).length
  const indirect = members.filter(
    (file) => !mapping.get(file).direct.length && mapping.get(file).indirect.length,
  ).length
  output += `| ${group} | ${members.length} | ${direct} | ${indirect} | ${members.length - direct - indirect} |\n`
}
for (const group of groups) {
  output += `\n## ${group}\n\n| Source | Priority | Importers | Direct suites | Indirect discovery |\n| --- | --- | ---: | --- | --- |\n`
  const members = sources
    .filter((file) => category(file) === group)
    .sort(
      (a, b) => priority(a).localeCompare(priority(b)) || usage(b) - usage(a) || a.localeCompare(b),
    )
  for (const file of members) {
    const { direct, indirect } = mapping.get(file)
    output += `| ${link(file)} | ${priority(file)} | ${usage(file)} | ${direct.map(link).join('<br>') || 'None'} | ${indirect.map(link).join('<br>') || 'None'} |\n`
  }
}
output +=
  '\n## Existing suite scenarios\n\nThese titles describe declared scenarios, not independently verified assertion coverage. Parameterized cases may contain additional scenarios.\n'
for (const test of tests) {
  const titles = [...contents.get(test).matchAll(/\b(?:it|test)\s*\(\s*(['"`])([^\n]*?)\1/g)].map(
    (match) => match[2],
  )
  output += `\n### ${link(test)}\n\n${titles.map((title) => `- ${title}`).join('\n') || '- Parameterized or dynamically declared scenarios; inspect this suite.'}\n`
}
const destination = path.join(root, 'docs/test-inventory.md')
output = await format(output, { ...(await resolveConfig(destination)), parser: 'markdown' })
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== output)
    throw new Error('Test inventory is stale. Run npm run test:inventory.')
} else await writeFile(destination, output)
console.log(
  `Mapped ${sources.length} source files against ${tests.length} suites. Import references do not establish behavior coverage.`,
)
